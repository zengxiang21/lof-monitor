def _match_stock(name: str) -> list[str]:
    """股票名 → 命中的方向列表（可能多个，取并集权重）。"""
    hits = []
    for tag, kws in STOCK_RULES:
        if any(k in name for k in kws):
            hits.append(tag)
    return hits


def _match_name(name: str) -> str | None:
    for tag, kws in NAME_RULES:
        if any(k in name for k in kws):
            return tag
    return None


def classify(fund_name: str, holdings: list[dict]) -> dict:
    """归类方向。holdings: [{name, weight, ...}]，按权重降序更佳。

    返回 {"tags": [...], "text": "...", "quarter": "...", "matched": bool}
    """
    quarter = None
    if holdings:
        quarter = holdings[0].get("quarter") or None
    # 1) 持仓关键词权重累加（同一股票命中多方向时均计入，符合"混投"实际）
    wsum: dict[str, float] = {}
    for h in holdings:
        nm = h.get("name") or ""
        w = float(h.get("weight") or 0)
        if w <= 0:
            continue
        for tag in _match_stock(nm):
            wsum[tag] = wsum.get(tag, 0.0) + w
    # 2) 基金名兜底：持仓关键词未命中时用（权重记 0）
    if not wsum and fund_name:
        t = _match_name(fund_name)
        if t:
            wsum[t] = 0.0
    # 3) 降序取 top2；权重 0 的兜底标签排最后
    tags = sorted(wsum.items(), key=lambda kv: -kv[1])[:2]
    tag_list = [{"tag": t, "w": round(w, 1)} for t, w in tags if w > 0]
    if not tag_list and tags:                       # 全是 0 权兜底（基金名命中）
        tag_list = [{"tag": tags[0][0], "w": 0}]
    elif not tag_list and holdings:                 # 有持仓但无关键词命中：分散持仓
        tag_list = [{"tag": "综合", "w": 0}]
    text = " / ".join(f"{t['tag']} {t['w']:.0f}%" if t["w"] > 0 else t["tag"]
                      for t in tag_list)
    return {"tags": tag_list, "text": text,
            "quarter": quarter, "matched": bool(tag_list)}
